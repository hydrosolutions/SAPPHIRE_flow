def _error_response(description: str) -> dict[str, Any]:
    return {
        "description": description,
        "content": {
            "application/json": {
                "schema": {"$ref": "#/components/schemas/ErrorResponse"}
            }
        },
    }


def _select_routes() -> list[APIRoute]:
    api_routes = [route for route in app.routes if isinstance(route, APIRoute)]
    selected = [
        route
        for route in api_routes
        if any((method, route.path) in _MAP_ROUTES for method in route.methods)
    ]
    found = {
        (method, route.path)
        for route in selected
        for method in route.methods
        if (method, route.path) in _MAP_ROUTES
    }
    missing = _MAP_ROUTES - found
    if missing:
        raise RuntimeError(f"map_contract: routes missing from app.routes: {missing}")
    return selected


class _SnapshotOpenApiSchema(GenerateJsonSchema):
    def tagged_union_schema(
        self, schema: core_schema.TaggedUnionSchema
    ) -> JsonSchemaValue:
        result = super().tagged_union_schema(schema)
        # OpenAPI discriminator properties are strings; boolean unions use oneOf/const.
        if all(isinstance(choice, bool) for choice in schema["choices"]):
            result.pop("discriminator", None)
        return result


def _contract_routes() -> list[APIRoute]:
    routes = _select_routes()
    result: list[APIRoute] = []
    for route in routes:
        if route.path == _SNAPSHOT_PATH:
            route = copy(route)
            route.response_field = None
        result.append(route)
    return result


def _add_snapshot_schema(doc: dict[str, Any]) -> None:
    schema = ForecastLabSnapshot.model_json_schema(
        ref_template="#/components/schemas/{model}",
        schema_generator=_SnapshotOpenApiSchema,
        mode="serialization",
    )
    definitions = schema.pop("$defs", {})
    definitions["ForecastLabSnapshot"] = schema
    components = doc.setdefault("components", {}).setdefault("schemas", {})
    for name, definition in definitions.items():
        if name in components and components[name] != definition:
            raise ValueError(f"OpenAPI schema component collision: {name}")
        components[name] = definition
    operation = doc["paths"][_SNAPSHOT_PATH]["get"]
    operation["responses"]["200"]["content"]["application/json"]["schema"] = {
        "$ref": "#/components/schemas/ForecastLabSnapshot"
    }
    operation["description"] += (
        " All responses are no-store. Omitted station_code selects eligible scoped "
        "stations; any unknown, ineligible or out-of-scope requested code rejects "
        "the whole request. This comparison view is not authoritative evaluation."
    )
    for status, description in {
        "403": "Forecast Lab is unavailable for publication-gated stations.",
        "404": "Unknown, ineligible or out-of-scope station.",
        "500": "Snapshot unavailable due to an internal or configuration error.",
        "503": "Ordinary forecast reads are unavailable.",
    }.items():
        operation["responses"][status] = _error_response(description)


def build_map_openapi() -> dict[str, Any]:
    doc = get_openapi(
        title="SAPPHIRE Flow — flow map contract",
        version=MAP_CONTRACT_VERSION,
        description=(
            "The subset of /api/v1 the flow map reads (Plan 402). Not "
            "served — openapi_url stays None on the live app; this is a "
            "committed, drift-tested static artefact. Bearer auth is added "
            "explicitly below: the live routes read the Authorization "
            "header from the raw Request, so FastAPI's own generator sees "
            "no security scheme."
        ),
        routes=_contract_routes(),
    )
    _add_snapshot_schema(doc)

    doc.setdefault("components", {}).setdefault("schemas", {})["ErrorResponse"] = (
        ErrorResponse.model_json_schema()
    )
    doc["components"]["securitySchemes"] = {
        "bearerAuth": {"type": "http", "scheme": "bearer"}
    }

    paths: dict[str, dict[str, dict[str, Any]]] = doc["paths"]
    for path, path_item in paths.items():
        for method, operation in path_item.items():
            operation["security"] = [{"bearerAuth": []}]
            summary, tag = _OPERATION_LABELS[path]
            operation["summary"] = summary
            operation["tags"] = [tag]
            description = _DESCRIPTIONS.get((method.upper(), path))
            if description is not None:
                operation["description"] = description
            responses: dict[str, Any] = operation.setdefault("responses", {})
            if path in _400_PATHS:
                responses["400"] = _error_response(
                    "Malformed query value or station_id "
                    '(error envelope: {"error": <message>, "detail": null}).'
                )
            responses["401"] = _error_response("Missing or invalid access token.")
            if path in _REVIEW_PATHS:
                responses["403"] = _error_response("Reviewer or admin token required.")
            if path in _REVIEW_OR_HUMAN_PATHS:
                responses["403"] = _error_response(
                    "Reviewer or admin token, or a granted human, required."
                )
            if path in _404_PATHS:
                responses["404"] = _error_response(
                    "Unknown or out-of-scope station/forecast — the same "
                    "body either way (never reveals which)."
                )
            if path == "/api/v1/stations/{station_id}/skill-diagrams":
                responses["422"]["description"] = (
                    "Invalid selectors or stored diagrams exceed response limit."
                )
                responses["422"]["content"]["application/json"]["schema"] = {
                    "anyOf": [
                        {"$ref": "#/components/schemas/HTTPValidationError"},
                        {"$ref": "#/components/schemas/ErrorResponse"},
                    ]
                }
            if path == "/api/v1/stations/{station_id}/skill-options":
                responses["503"] = _error_response(
                    "Stored skill catalogue exceeds admission limit."
                )
            if path in {
                "/api/v1/stations",
                "/api/v1/stations/{station_id}",
                "/api/v1/stations/{station_id}/forecasts",
                "/api/v1/forecasts/{forecast_id}",
            }:
                operation["description"] += (
                    " All responses, outer errors, slash redirects and allowed "
                    "preflights "
                    "are no-store."
                )
                responses["500"] = _error_response("Sanitized internal error.")
                responses["503"] = _error_response(
                    "Scoped provisional reads unavailable."
                )
                if (
                    path.endswith("/forecasts")
                    or path == "/api/v1/forecasts/{forecast_id}"
                ):
                    operation["description"] += (
                        " The preceding publication rules apply to standard requests. "
                        "Explicit data_use=provisional_rating requires reviewer/admin"
                        " and "
                        "station/tenant scope. Superseded history remains readable; no "
                        "provisional410. Validated frozen warnings accompany "
                        "PROVISIONAL; "
                        "rating_curves=[] with rating_provenance_status=not_exposed "
                        "means "
                        "exact versions are not listed, not missing lineage. "
                        "Publication "
                        "does not apply; its decision fields are null. No purpose "
                        "fallback."
                    )
                    responses["403"] = _error_response(
                        "Provisional purpose requires reviewer or admin."
                    )
                else:
                    operation["description"] += (
                        " Required nullable has_provisional_forecast is scoped "
                        "existence "
                        "of a stored non-superseded provisional row for "
                        "reviewer/admin; "
                        "consumer gets null without an availability query. False does"
                        " not "
                        "hide readable superseded history. No freshness, "
                        "lineage-health "
                        "or scientific-acceptance claim."
                    )
            if path == "/api/v1/forecasts/{forecast_id}/rating-input-history":
                responses["404"] = _error_response("Unknown or out-of-scope forecast.")
                responses["500"] = _error_response("Sanitized internal error.")
                responses["503"] = _error_response(
                    "Frozen rating evidence unavailable."
                )
            if path == "/api/v1/stations/{station_id}/observation-history":
                responses["403"] = _error_response(
                    "Provisional purpose requires reviewer or admin."
                )
                responses["404"] = _error_response("Unknown or out-of-scope station.")
                responses["500"] = _error_response("Sanitized internal error.")
                responses["503"] = _error_response("Observation history unavailable.")
            if path == "/api/v1/swiss/observation-history":
                responses["405"] = {
                    "description": "Method not allowed (framework detail envelope)."
                }
